/**
 * Import the worker the way `node --test` does — through the repo's type-stripping resolve hook,
 * registered here so the published command stays a plain `node scripts/verify-tracker-live.mjs`.
 * The hook also stubs `server-only`, which is what lets a bare Node process import modules the
 * Next.js compiler would otherwise refuse to hand out.
 */
async function loadWorker() {
  await import("./ts-resolve-hook.mjs");
  process.env.FEATURE_ANALYSIS = "1";
  process.env.FEATURE_TRACKER = "1";
  process.env.NEXT_PUBLIC_SUPABASE_URL = stack.API_URL;
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY = stack.ANON_KEY;
  process.env.SUPABASE_SERVICE_ROLE_KEY = stack.SERVICE_ROLE_KEY;
  return import("@/lib/analysis/worker");
}

// ---------------------------------------------------------------------------------------------
// --prepare
// ---------------------------------------------------------------------------------------------

async function prepare() {
  if (fs.existsSync(METADATA_PATH)) {
    const age = Date.now() - fs.statSync(METADATA_PATH).mtimeMs;
    if (age < STALE_RUN_MS) {
      fail(
        `a prepared run is already in flight (${Math.round(age / 1000)}s old) — finish it with ` +
          "`node scripts/verify-tracker-live.mjs --assert-and-cleanup` first",
      );
    }
    const stale = JSON.parse(fs.readFileSync(METADATA_PATH, "utf8"));
    say(`stale run reclaimed: ${stopChild(stale.serverPid, stale.serverPort)}`);
    removeMetadata();
  }

  cleanupReservedRows();

  let port = null;
  let pid = null;
  try {
    // 1. A fictional consumer, provisioned the only way a header-selected demo session can be:
    //    an auth user so the id is real, and a profile in the seeded operator's org so the create
    //    route's same-org check passes.
    //
    //    The profile row is *not* inserted directly. `on_auth_user_created` fires `handle_new_user`
    //    on the auth insert and writes the profile itself from `raw_user_meta_data`, so a second
    //    insert collides on the primary key. Supplying the metadata is the supported way to steer
    //    that trigger; the update after it is belt and braces for the two columns the trigger does
    //    not carry, and it also proves the row exists rather than assuming the trigger ran.
    runSql(`
begin;
insert into auth.users (id, instance_id, aud, role, email, email_confirmed_at, raw_user_meta_data, created_at, updated_at)
values (
  '${CONSUMER_PROFILE_ID}', '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated',
  '${CONSUMER_EMAIL}', now(),
  jsonb_build_object('app_role', 'consumer', 'org_id', '${OPERATOR_ORG_ID}', 'full_name', '${CONSUMER_NAME}'),
  now(), now()
);
update public.profiles
set org_id = '${OPERATOR_ORG_ID}', role = 'consumer', org_role = null,
    full_name = '${CONSUMER_NAME}', email = '${CONSUMER_EMAIL}', phone = '+15555550100', manages = '{}'
where id = '${CONSUMER_PROFILE_ID}';
commit;
`);
    const provisioned = runSql(
      `select count(*) from public.profiles where id = '${CONSUMER_PROFILE_ID}' and org_id = '${OPERATOR_ORG_ID}' and role = 'consumer';`,
    );
    if (provisioned !== "1") fail("the fictional consumer profile was not provisioned");

    port = await freePort();
    activeChild.port = port;
    const started = await startChildServer(port);
    pid = started.pid;
    activeChild.pid = pid;
    const { baseUrl } = started;
    say(`child application server ready on port ${port} (pid ${pid})`);

    // 2. Create the client through the real route, as the operator.
    const created = await call(baseUrl, "POST", "/api/clients", OPERATOR_PROFILE_ID, {
      consumerProfileId: CONSUMER_PROFILE_ID,
      displayName: CONSUMER_NAME,
    });
    if (created.status !== 201) {
      fail(`POST /api/clients returned ${created.status} (${created.payload?.error?.code ?? "no code"})`);
    }
    assert.equal(created.payload.outcome, "created");
    assert.equal(created.payload.client.stage, "onboarding");
    const clientId = created.payload.client.id;
    say(`client created: ${clientId} stage=onboarding`);

    // 3. Enroll and pass IDV as the consumer. Activation is what fires the enrollment adapter.
    const draftId = crypto.randomUUID();
    const enrolled = await call(baseUrl, "POST", "/api/enroll", CONSUMER_PROFILE_ID, {
      analysis: true,
      draftId,
      email: CONSUMER_EMAIL,
      monitoring: true,
      name: CONSUMER_NAME,
      phone: "+15555550100",
      signature: CONSUMER_NAME,
    });
    if (enrolled.status !== 200) {
      fail(`POST /api/enroll returned ${enrolled.status} (${enrolled.payload?.error?.code ?? "no code"})`);
    }
    const enrollmentId = enrolled.payload.enrollmentId;
    assert.ok(enrollmentId, "POST /api/enroll returned no enrollment id");

    const active = await call(
      baseUrl,
      "POST",
      `/api/enrollments/${enrollmentId}/idv`,
      CONSUMER_PROFILE_ID,
      { code: "246810", kind: "sms" },
    );
    if (active.status !== 200) {
      fail(`POST /api/enrollments/:id/idv returned ${active.status} (${active.payload?.error?.code ?? "no code"})`);
    }
    assert.equal(active.payload.status, "active");
    say(`enrollment ${enrollmentId} active`);

    // 4. Snapshot the timer *before* the analysis event, so "the second event did not restart the
    //    60-day clock" is a comparison against a recorded value rather than an assumption.
    const afterEnrollment = labelled(
      runSql(`
select 'stage:' || stage::text from public.clients where id = '${clientId}';
select 'entered:' || (to_json(stage_entered_at) #>> '{}') from public.clients where id = '${clientId}';
select 'queued:' || count(*)::text from public.analysis_jobs where client_id = '${clientId}';
`),
    );
    const stageAfterEnrollment = one(afterEnrollment, "stage");
    const enteredAfterEnrollment = one(afterEnrollment, "entered");
    if (stageAfterEnrollment !== "optimization") {
      fail(
        `the enrollment event left the client in '${stageAfterEnrollment}' — the tracker enrollment ` +
          "adapter did not reach the transition RPC",
      );
    }
    if (one(afterEnrollment, "queued") !== "1") {
      fail("activation did not enqueue exactly one analysis job — the analysis enqueue call did not run");
    }
    say(`enrollment event: stage=optimization, 1 analysis job queued`);

    // 5. Drain. This process is the worker; the analysis adapter fires from inside it.
    const worker = await loadWorker();
    const workerId = crypto.randomUUID();
    const drain = await worker.drainAnalysisQueue({ maxJobs: 5, workerId });
    say(`first drain: claimed=${drain.claimed} succeeded=${drain.succeeded} failed=${drain.failed}`);
    if (drain.succeeded < 1) {
      const why = labelled(
        runSql(
          `select 'err:' || coalesce(error_code::text, 'none') from public.analysis_jobs where client_id = '${clientId}';`,
        ),
      );
      fail(`the analysis job did not succeed (error_code=${(why.get("err") ?? ["unknown"]).join(",")})`);
    }

    const runRow = labelled(
      runSql(`
select 'run:' || id::text from public.analysis_runs where client_id = '${clientId}';
select 'readiness:' || readiness_score::text from public.analysis_runs where client_id = '${clientId}';
`),
    );
    const analysisRunId = one(runRow, "run");
    const readiness = Number(one(runRow, "readiness"));

    // 7. Read the client back the way the operator surface does.
    const listed = await call(baseUrl, "GET", "/api/clients", OPERATOR_PROFILE_ID);
    assert.equal(listed.status, 200);
    assert.equal(listed.payload.enabled, true);
    const seen = listed.payload.clients.find((row) => row.id === clientId);
    assert.ok(seen, "GET /api/clients did not return the prepared client to the operator");
    say(`operator read: stage=${seen.stage} readiness=${seen.readiness} monitoring=${seen.monitoring}`);

    const metadata = {
      analysisRunId,
      apiReadiness: seen.readiness,
      apiStage: seen.stage,
      apiStageEnteredAt: seen.stageEnteredAt,
      clientId,
      consumerProfileId: CONSUMER_PROFILE_ID,
      enrollmentId,
      operatorProfileId: OPERATOR_PROFILE_ID,
      persistedReadiness: readiness,
      preparedAt: new Date().toISOString(),
      serverPid: pid,
      serverPort: port,
      serverUrl: baseUrl,
      stageAfterEnrollmentEvent: stageAfterEnrollment,
      stageEnteredAtAfterEnrollmentEvent: enteredAfterEnrollment,
    };

    // The deny-list is checked against the serialized file, not against the object, because the
    // thing that must be clean is what lands on disk.
    const serialized = `${JSON.stringify(metadata, null, 2)}\n`;
    for (const secret of secrets) {
      if (serialized.includes(secret)) fail("the metadata file would have contained a secret value");
    }
    for (const banned of ["postgresql://", "postgres://", "mock_", "service_role"]) {
      if (serialized.includes(banned)) fail(`the metadata file would have contained \`${banned}\``);
    }
    fs.writeFileSync(METADATA_PATH, serialized);

    // The URL is the demo shell root, not `/operator`. With `FEATURE_REAL_AUTH` off — which is the
    // demo configuration — `/operator` redirects to `/`, and the surfaces are reached by switching
    // role inside the shell. Switching to Operator is also what writes the `mf_demo_profile_id`
    // cookie the tracker read needs, so the path through the switcher is the working one.
    say("");
    say(`prepared. open ${baseUrl}/ and switch to the Operator role.`);
    say(`  look for "${CONSUMER_NAME}" in Optimization`);
    say(`  stage entered at ${enteredAfterEnrollment} (the timer runs from here)`);
    say(`  then run: node scripts/verify-tracker-live.mjs --assert-and-cleanup`);
  } catch (error) {
    if (pid !== null) say(`prepare failed — ${stopChild(pid, port)}`);
    cleanupReservedRows();
    removeMetadata();
    throw error;
  }
}

// ---------------------------------------------------------------------------------------------
// --assert-and-cleanup
// ---------------------------------------------------------------------------------------------

async function assertAndCleanup() {
  if (!fs.existsSync(METADATA_PATH)) {
    fail("no prepared run found — run `node scripts/verify-tracker-live.mjs --prepare` first");
  }
  const run = JSON.parse(fs.readFileSync(METADATA_PATH, "utf8"));

  try {
    const enrollmentKey = `enrollment:${run.enrollmentId}:active`;
    const analysisKey = `analysis:${run.analysisRunId}:complete`;

    const state = labelled(
      runSql(`
select 'clients:' || count(*)::text from public.clients where id = '${run.clientId}';
select 'stage:' || stage::text from public.clients where id = '${run.clientId}';
select 'entered:' || (to_json(stage_entered_at) #>> '{}') from public.clients where id = '${run.clientId}';
select 'history_count:' || count(*)::text from public.stage_history where client_id = '${run.clientId}';
select 'history_move:' || from_stage::text || '>' || to_stage::text from public.stage_history where client_id = '${run.clientId}';
select 'history_at:' || (to_json(changed_at) #>> '{}') from public.stage_history where client_id = '${run.clientId}';
select 'audit_count:' || count(*)::text from public.audit_log where client_id = '${run.clientId}' and action = 'client.stage.transitioned';
select 'audit_at:' || (to_json(occurred_at) #>> '{}') from public.audit_log where client_id = '${run.clientId}' and action = 'client.stage.transitioned';
select 'receipt_count:' || count(*)::text from public.tracker_transition_receipts where client_id = '${run.clientId}';
select 'receipt:' || event_key || '|' || source::text from public.tracker_transition_receipts where client_id = '${run.clientId}' order by event_key;
select 'runs:' || count(*)::text from public.analysis_runs where client_id = '${run.clientId}';
select 'plans:' || count(*)::text from public.plans where client_id = '${run.clientId}';
select 'job:' || status::text || '|' || attempt_count::text || '|' || coalesce(error_code::text, 'none') from public.analysis_jobs where client_id = '${run.clientId}';
`),
    );

    assert.equal(one(state, "clients"), "1", "the prepared client is gone from the database");

    // One transition, from Onboarding to Optimization, and exactly one of each durable trace.
    assert.equal(one(state, "stage"), "optimization");
    assert.equal(one(state, "history_count"), "1", "expected exactly one stage_history row after both events");
    assert.equal(one(state, "history_move"), "onboarding>optimization");
    assert.equal(one(state, "audit_count"), "1", "expected exactly one transition audit_log row after both events");

    // One timestamp for all three writes: the RPC does them in one transaction with one `now()`,
    // and a divergence here means somebody split it.
    const persistedEntered = one(state, "entered");
    assert.equal(one(state, "history_at"), persistedEntered, "stage_history disagrees with clients.stage_entered_at");
    assert.equal(one(state, "audit_at"), persistedEntered, "audit_log disagrees with clients.stage_entered_at");

    // The timer did not restart. `--prepare` recorded this value before the analysis event ran.
    assert.equal(
      persistedEntered,
      run.stageEnteredAtAfterEnrollmentEvent,
      "the analysis event moved stage_entered_at — the 60-day timer restarted",
    );

    // Both events were consumed durably, under the exact keys the 07-01 adapters build. A typo in
    // either adapter changes one of these strings and fails here.
    assert.equal(one(state, "receipt_count"), "2");
    assert.deepEqual(
      (state.get("receipt") ?? []).toSorted(),
      [`${analysisKey}|analysis`, `${enrollmentKey}|enrollment`].toSorted(),
    );

    assert.equal(one(state, "runs"), "1");
    assert.equal(one(state, "plans"), "1");
    assert.equal(one(state, "job"), "succeeded|1|none");

    // The operator's read returns the persisted values, not a cached or recomputed approximation.
    const listed = await call(run.serverUrl, "GET", "/api/clients", run.operatorProfileId);
    assert.equal(listed.status, 200, "the prepared server stopped answering before the assertions ran");
    const seen = listed.payload.clients.find((row) => row.id === run.clientId);
    assert.ok(seen, "GET /api/clients no longer returns the prepared client");
    assert.equal(seen.stage, "optimization");
    assert.equal(seen.stageEnteredAt, persistedEntered, "the API stage timestamp differs from the persisted one");
    assert.equal(seen.readiness, run.persistedReadiness);

    // Criterion 5, observed on this tree in this run rather than cited from Phase 5's record.
    const worker = await loadWorker();
    const second = await worker.drainAnalysisQueue({ maxJobs: 5, workerId: crypto.randomUUID() });
    assert.equal(second.claimed, 0, `a second drain claimed ${second.claimed} jobs — the queue is not idempotent`);

    say("live chain verified by database read-back:");
    say(`  client ${run.clientId} stage=optimization entered_at=${persistedEntered}`);
    say(`  stage_history 1 row (onboarding>optimization), transition audit_log 1 row, all three timestamps equal`);
    say(`  receipts 2: ${enrollmentKey} (enrollment), ${analysisKey} (analysis)`);
    say(`  analysis run ${run.analysisRunId} readiness=${run.persistedReadiness}, job succeeded on attempt 1`);
    say(`  operator GET /api/clients matches the persisted stage and timestamp`);
    say(`  second drain claimed ${second.claimed}`);
  } finally {
    say(`cleanup: ${stopChild(run.serverPid, run.serverPort)}`);
    cleanupReservedRows();
    removeMetadata();

    // Prove the cascade fired rather than assuming it. The client row going away is not the same
    // claim as its children going away, and the difference is exactly the orphan bug the comment on
    // `cleanupReservedRows` records. These counts are keyed on the run's own recorded ids.
    const leftovers = labelled(
      runSql(`
select 'clients:' || count(*)::text from public.clients where consumer_profile_id::text like '${RESERVED_PREFIX}%';
select 'profiles:' || count(*)::text from public.profiles where id::text like '${RESERVED_PREFIX}%';
select 'enrollments:' || count(*)::text from public.enrollments where id = '${run.enrollmentId}';
select 'consents:' || count(*)::text from public.consents where client_id = '${run.clientId}';
select 'esignatures:' || count(*)::text from public.esignatures where client_id = '${run.clientId}';
select 'audit:' || count(*)::text from public.audit_log where client_id = '${run.clientId}';
select 'history:' || count(*)::text from public.stage_history where client_id = '${run.clientId}';
select 'receipts:' || count(*)::text from public.tracker_transition_receipts where client_id = '${run.clientId}';
select 'runs:' || count(*)::text from public.analysis_runs where client_id = '${run.clientId}';
select 'jobs:' || count(*)::text from public.analysis_jobs where client_id = '${run.clientId}';
`),
    );
    const left = [...leftovers.entries()].filter(([, counts]) => counts.some((count) => count !== "0"));
    say(
      `cleanup: ${left.length === 0 ? "0 rows remain across 10 tables" : left.map(([table, counts]) => `${table}=${counts.join()}`).join(" ")}` +
        ", metadata file removed",
    );
    if (left.length !== 0) fail("cleanup left rows behind");
  }
}

// ---------------------------------------------------------------------------------------------

let interrupted = false;
for (const signal of ["SIGINT", "SIGTERM"]) {
  process.on(signal, () => {
    if (interrupted) process.exit(130);
    interrupted = true;
    try {
      if (activeChild.pid !== null) {
        stopChild(activeChild.pid, activeChild.port);
      } else if (fs.existsSync(METADATA_PATH)) {
        const run = JSON.parse(fs.readFileSync(METADATA_PATH, "utf8"));
        stopChild(run.serverPid, run.serverPort);
      }
      cleanupReservedRows();
      removeMetadata();
      say(`${signal} — reserved rows and child process cleaned up`);
    } catch {
      say(`${signal} — cleanup could not complete; run --assert-and-cleanup to finish`);
    }
    process.exit(130);
  });
}

try {
  if (mode === "--prepare") await prepare();
  else await assertAndCleanup();
} catch (error) {
  process.stderr.write(`${redact(error?.stack ?? error?.message ?? String(error))}\n`);
  process.exit(1);
}
