/**
 * The static half of the no-auto-send property (SUPP-01, SUPP-02, DEC-D10).
 *
 * `src/lib/support/no-auto-send.test.ts` drives the real draft lifecycle over 64 generated
 * conversations and counts sends, and `scripts/verify-support-api.mjs` does the same over HTTP
 * against the real database. Both prove the property for the code that exists today. Neither can
 * see the file somebody adds next month, and that file is the realistic way this breaks: not a
 * deliberate auto-reply feature, but a "just retry it in the background" helper that happens to
 * reach the send seam.
 *
 * So this is the third proof, and the cheap one — no database, no build, no server, under a
 * second. It reads source text and an import graph and answers one question: is there exactly one
 * way to create a support message, and does every path to it start at a person pressing send?
 *
 * Five rules:
 *
 *   1. Single caller     — the send RPC literal appears in one file under web/src and two under
 *                          supabase/, and nowhere else.
 *   2. No deferred writers — nothing under the support library or the support routes defers work
 *                          to a timer, a microtask, `after()`, or a cron.
 *   3. Reachability      — the transitive set of modules carrying the send seam has exactly one
 *                          entry point, and it is the messages route.
 *   4. No AI-author vocabulary — no `autoSend`/`autoReply` identifier, and no `'ai'` used as an
 *                          author kind. A message is written by a person or it is not written.
 *   5. No drafts segment — no route or page directory that a cross-thread held-replies queue
 *                          could live in (#192).
 *
 * `--self-test` plants one violation of each rule in a temporary tree and fails unless all five
 * are caught. Without it a scanner that quietly stopped matching anything would report a clean
 * tree forever, which is worse than no scanner: it would be a green check with nothing behind it.
 *
 * This file edits nothing and reads nothing outside the repository.
 */

