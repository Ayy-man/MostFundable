/** Rule 2's vocabulary. `after(` is Next's request-deferral primitive, banned outright by DEC-D10. */
const DEFERRAL_PATTERNS = [
  { name: "after", pattern: /(?<![.\w])after\s*\(/ },
  { name: "setTimeout", pattern: /(?<![.\w])setTimeout\s*\(/ },
  { name: "setInterval", pattern: /(?<![.\w])setInterval\s*\(/ },
  { name: "queueMicrotask", pattern: /(?<![.\w])queueMicrotask\s*\(/ },
  { name: "setImmediate", pattern: /(?<![.\w])setImmediate\s*\(/ },
  { name: "cron", pattern: /\bcron\b/i },
];

/** Rule 4's vocabulary. */
const AUTHOR_PATTERNS = [
  { name: "autoSend", pattern: /\bauto[_]?[Ss]end\b/ },
  { name: "autoReply", pattern: /\bauto[_]?[Rr]eply\b/ },
  { name: "ai-author-kind", pattern: /author[_ ]?[Kk]ind\s*[:=]\s*['"]ai['"]/ },
  { name: "ai-author-cast", pattern: /'ai'\s*::\s*(public\.)?support_author_kind/ },
];

/** Rule 5's vocabulary. */
const FORBIDDEN_SEGMENTS = /^(drafts|held-drafts|held_replies|held-replies)$/;

/** Modules that must never appear on a path to the send seam. */
const BACKGROUND_HINT = /(^|[/_.-])(webhook|worker|job|jobs|queue|cron|scheduler|task)s?([/_.-]|\.[tj]sx?$)/i;

