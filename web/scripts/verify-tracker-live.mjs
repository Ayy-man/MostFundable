/**
 * The live chain verifier Phase 6 specified and could not write.
 *
 * Phase 6 wired `onEnrollmentActivated` and `onAnalysisCompleted` to a durable RPC and proved the
 * RPC in isolation, but nothing called either function, so the criterion "create consumer → enroll →
 * pipeline runs → operator tracker shows the client advance with real timestamps" was recorded as
 * PENDING. Phase 7 plan 01 added the two adapters that make those calls; this script is the proof
 * that the chain they complete actually runs.
 *
 * Two bounded modes, on purpose:
 *
 *   node scripts/verify-tracker-live.mjs --prepare
 *   node scripts/verify-tracker-live.mjs --assert-and-cleanup
 *
 * `--prepare` runs the chain and then *stops*, leaving one fictional client sitting in Optimization
 * and one child application server answering, so a human can open the operator surface and see the
 * row a moment before it is deleted. That human observation is the thing an assertion cannot
 * substitute for, and splitting the modes is what buys the window in which to make it.
 *
 * Everything this script asserts, it asserts by reading the database back. A 2xx response, a
 * resolved queue promise or a Realtime event proves that code ran, not that a row moved, and the
 * failure this verifier exists to catch — a transition that silently no-ops — looks exactly like
 * success from the HTTP side.
 *
 * Safety rules this file must keep:
 *   - It never runs `supabase db reset`, `supabase stop` or any migration. One local stack serves
 *     every worktree on this machine, so a reset here destroys another agent's work in progress.
 *   - Every row it creates carries the reserved `7c000000-…` UUID prefix, and cleanup deletes by
 *     that prefix, so an interrupted run is recoverable without knowing what it got as far as.
 *   - It kills exactly one process: the child it spawned, identified by PID *and* by a command line
 *     that still mentions the port it was given. A PID is reused; a stale metadata file must never
 *     become a licence to signal somebody else's process.
 *   - Nothing it prints or writes contains a connection string, a service-role key, a member
 *     reference or any provider content. Ids, counts, statuses and ISO timestamps only.
 */

import assert from "node:assert/strict";
import { spawn, spawnSync } from "node:child_process";
import { createServer } from "node:net";
import fs from "node:fs";
import path from "node:path";
import { setTimeout as delay } from "node:timers/promises";

const WEB_ROOT = path.resolve(import.meta.dirname, "..");
const REPO_ROOT = path.resolve(WEB_ROOT, "..");
const METADATA_PATH = path.join(
  REPO_ROOT,
  ".planning/phases/07-demo-hardening-milestone-2-script/07-live-run.json",
);

/**
 * Every row this run owns is addressable by this prefix alone.
 *
 * `clients.id` is generated by the database — `POST /api/clients` takes no id — so the prefix lives
 * on the one id the script does choose, the fictional consumer's profile, and the client is reached
 * through `consumer_profile_id`. That indirection is what makes cleanup work after a crash: the
 * script does not need to have recorded the client id to be able to delete it.
 */
const RESERVED_PREFIX = "7c000000";
const CONSUMER_PROFILE_ID = "7c000000-0000-4000-8000-000000000001";
const CONSUMER_EMAIL = "tracker-live-verifier@example.invalid";
const CONSUMER_NAME = "Riley Live Chain Fixture";

/** The seeded Northbridge owner. The verifier borrows the demo identity mechanism, nothing more. */
const OPERATOR_PROFILE_ID = "a1000000-0000-0000-0000-000000000001";
const OPERATOR_ORG_ID = "a0000000-0000-0000-0000-000000000001";

/** An abandoned `--prepare` older than this is stale; a younger one is somebody else mid-run. */
const STALE_RUN_MS = 45 * 60 * 1000;
const SERVER_READY_TIMEOUT_MS = 120_000;

const MODES = new Set(["--prepare", "--assert-and-cleanup"]);
const mode = process.argv[2];

if (!MODES.has(mode) || process.argv.length > 3) {
  process.stderr.write(
    "usage: node scripts/verify-tracker-live.mjs (--prepare | --assert-and-cleanup)\n",
  );
  process.exit(2);
}

