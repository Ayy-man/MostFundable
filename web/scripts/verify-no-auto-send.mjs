/**
 * @param {{ webRoot: string, repoRoot: string }} roots
 * @returns {{ findings: Array, fileCount: number }}
 */
function scan(roots) {
  const srcRoot = path.join(roots.webRoot, "src");
  const appRoot = path.join(srcRoot, "app");
  const supabaseRoot = path.join(roots.repoRoot, "supabase");
  const findings = [];
  const relative = (file) => path.relative(roots.repoRoot, file).split(path.sep).join("/");
  const webRelative = (file) => path.relative(roots.webRoot, file).split(path.sep).join("/");

  const record = (rule, file, line, detail) =>
    findings.push({ rule, file: relative(file), line, detail });

  const sourceFiles = collectFiles(srcRoot, isSource);
  const sqlFiles = [
    ...collectFiles(path.join(supabaseRoot, "migrations"), (file) => file.endsWith(".sql")),
    ...collectFiles(path.join(supabaseRoot, "tests"), (file) => file.endsWith(".sql")),
  ];

  // -- Rule 1: one caller ----------------------------------------------------------------------
  for (const file of sourceFiles) {
    const source = fs.readFileSync(file, "utf8");
    if (!source.includes(SEND_RPC)) continue;
    if (PERMITTED_TS.has(webRelative(file))) continue;
    // Comments stripped, strings kept — see `stripComments` for why this branch cannot use the
    // stronger strip its SQL twin uses, and why it cannot go on reading the raw file either.
    const code = stripComments(source);
    if (!code.includes(SEND_RPC)) continue;
    record("single-caller", file, lineOf(source, code.indexOf(SEND_RPC)),
      "names the send RPC outside the two permitted TypeScript files");
  }
  for (const file of sqlFiles) {
    const source = fs.readFileSync(file, "utf8");
    if (!source.includes(SEND_RPC)) continue;
    if (PERMITTED_SQL.has(relative(file))) continue;
    // Comments are stripped first: migration 100 explains in prose that migration 101 will add
    // this function, and documenting the rule is not breaking it. `sql` is on here and nowhere
    // else in this file, because `--` is a comment in SQL and a decrement in TypeScript.
    const code = stripCommentsAndStrings(source, { sql: true });
    if (!code.includes(SEND_RPC)) continue;
    record("single-caller", file, lineOf(source, code.indexOf(SEND_RPC)),
      "names the send RPC outside the permitted SQL files");
  }

  // -- Rule 2: no deferred writers -------------------------------------------------------------
  //
  // Tests are excluded because they do not ship and because two of them assert *against* this
  // vocabulary by name, which would make the scanner flag its own sibling proof.
  // The scope is derived, not listed. It used to be these two directories, which is an
  // enumeration standing in for "everything that can cause a support message to be written" — and
  // the enumeration was wrong: `src/lib/operator/support-inbox.client.ts` holds every write the
  // operator Inbox makes, sits in neither directory, and an adversarial review planted a
  // `setTimeout` auto-retry of `postSupportReply` inside it that passed this scanner, both surface
  // contracts and every Inbox test. A resend of a support message five seconds later with nobody
  // present is rail 1 defeated in the one file none of the three guards looked at.
  //
  // Two ways a module can cause a write, so two ways in. Server-side it imports its way to the
  // send seam, which is the closure rule 3 already computes below. Client-side it crosses an HTTP
  // boundary that no import graph can follow, so it is found by naming a support route — and that
  // name reaches `fetch` as a string literal, which is why this strips comments only and leaves
  // strings intact. A file that merely *mentions* the route in prose is not in scope; a file that
  // requests it is.
  const namesASupportRoute = (file) =>
    stripComments(fs.readFileSync(file, "utf8")).includes("/api/support/");
  const deferralScope = [
    ...collectFiles(path.join(srcRoot, "lib/support"), (file) => isSource(file) && !isTest(file)),
    ...collectFiles(path.join(appRoot, "api/support"), isSource),
    ...sourceFiles.filter(
      (file) =>
        !isTest(file) &&
        !webRelative(file).startsWith("src/lib/support/") &&
        !webRelative(file).startsWith("src/app/api/support/") &&
        namesASupportRoute(file),
    ),
  ];
  for (const file of deferralScope) {
    const source = fs.readFileSync(file, "utf8");
    const code = stripCommentsAndStrings(source);
    for (const { name, pattern } of DEFERRAL_PATTERNS) {
      for (const hit of matchesIn(code, pattern)) {
        record("deferred-writer", file, lineOf(source, hit.index), `${name} in the support path`);
      }
    }
  }

  // -- Rule 3: reachability --------------------------------------------------------------------
  const graphFiles = sourceFiles.filter((file) => !isTest(file));
  const graph = buildImportGraph(graphFiles, srcRoot);
  const seed = path.join(srcRoot, "lib/support/repository.ts");
  // Comment-stripped, because several files in this phase explain the seam in prose — the routes'
  // header comments say they can only reach it through `sendMessage`, which is a description of
  // the property and must not be read as participation in it.
  const sourceCache = new Map();
  const sourceOf = (file) => {
    if (!sourceCache.has(file)) {
      sourceCache.set(file, stripCommentsAndStrings(fs.readFileSync(file, "utf8")));
    }
    return sourceCache.get(file);
  };
  const carriers = fs.existsSync(seed) ? sendSeamClosure(graph, seed, sourceOf) : new Set();

  const importedByACarrier = new Set();
  for (const file of carriers) {
    for (const edge of graph.get(file) ?? []) {
      if (carriers.has(edge.target)) importedByACarrier.add(edge.target);
    }
  }

  const messagesRoute = path.join(appRoot, "api/support/threads/[id]/messages") + path.sep;
  for (const file of carriers) {
    if (BACKGROUND_HINT.test(webRelative(file))) {
      record("reachability", file, 1, "a background-shaped module can reach the send seam");
    }
    if (importedByACarrier.has(file)) continue;
    // An entry point: nothing else on a send path imports it.
    if (!file.startsWith(messagesRoute)) {
      record("reachability", file, 1,
        "is an entry point to the send seam outside the messages route");
    }
  }

  // -- Rule 4: no AI-author vocabulary ---------------------------------------------------------
  const authorScope = [
    ...sourceFiles,
    ...collectFiles(path.join(supabaseRoot, "migrations"), (file) => /\/10\d_[^/]+\.sql$/.test(file.split(path.sep).join("/"))),
  ];
  for (const file of authorScope) {
    const source = fs.readFileSync(file, "utf8");
    // The only scope in this file holding both languages, so the `--` rule is chosen per file
    // rather than for the loop.
    const code = stripCommentsAndStrings(source, { sql: file.endsWith(".sql") });
    for (const { name, pattern } of AUTHOR_PATTERNS) {
      // The author-kind patterns look inside string literals, which `code` has blanked, so they
      // run against the original text; the identifier patterns run against code only.
      const haystack = name.startsWith("ai-") ? source : code;
      for (const hit of matchesIn(haystack, pattern)) {
        record("ai-author", file, lineOf(source, hit.index), name);
      }
    }
  }

  // -- Rule 5: no drafts segment ---------------------------------------------------------------
  for (const directory of collectDirectories(appRoot)) {
    if (FORBIDDEN_SEGMENTS.test(path.basename(directory))) {
      record("drafts-segment", directory, 1, "a cross-thread draft queue could live here");
    }
  }

  return { findings, fileCount: sourceFiles.length + sqlFiles.length };
}

