/**
 * `supabase status -o env` is the documented source for these values (docs/backend/LOCAL-STACK.md)
 * and the only one that works in a worktree with no `.env.local`. It is parsed, never echoed, and
 * every value it yields is registered as a secret before anything else can print it.
 */
function readStackEnv() {
  const status = spawnSync("supabase", ["status", "-o", "env"], {
    cwd: REPO_ROOT,
    encoding: "utf8",
    maxBuffer: 4 * 1024 * 1024,
  });

  if (status.status !== 0) {
    fail(
      "`supabase status -o env` failed — start the shared local stack with `supabase start` " +
        "from the repository root and try again.",
    );
  }

  const values = {};
  for (const line of status.stdout.split("\n")) {
    const match = /^([A-Z0-9_]+)="?(.*?)"?$/.exec(line.trim());
    if (match) values[match[1]] = match[2];
  }

  for (const key of ["API_URL", "ANON_KEY", "SERVICE_ROLE_KEY"]) {
    if (!values[key]) fail(`\`supabase status -o env\` did not report ${key}`);
  }
  // API_URL is a loopback address and not itself a secret, but the keys and the connection string
  // are, and DB_URL is optional only because the docker path does not need it.
  remember(values.ANON_KEY);
  remember(values.SERVICE_ROLE_KEY);
  if (values.DB_URL) remember(values.DB_URL);
  if (process.env.LOCAL_DATABASE_URL) remember(process.env.LOCAL_DATABASE_URL);

  return values;
}

const stack = readStackEnv();

const projectId = /^project_id\s*=\s*"([^"]+)"/m.exec(
  fs.readFileSync(path.join(REPO_ROOT, "supabase/config.toml"), "utf8"),
)?.[1];
assert.ok(projectId, "supabase/config.toml must declare project_id");

const databaseUrl = process.env.LOCAL_DATABASE_URL ?? stack.DB_URL ?? null;
const hasLocalPsql = spawnSync("psql", ["--version"], { stdio: "ignore" }).status === 0;
const useLocalPsql = hasLocalPsql && databaseUrl !== null;

/**
 * One SQL entry point, so the redaction and the ON_ERROR_STOP discipline are impossible to skip.
 *
 * `-Atq` gives unaligned, tuples-only output with no footer, which is what makes the labelled
 * `select 'name:' || value` idiom below parseable as plain lines.
 */
function runSql(sql) {
  const command = useLocalPsql ? "psql" : "docker";
  const args = useLocalPsql
    ? ["-X", "-v", "ON_ERROR_STOP=1", "-Atq"]
    : [
        "exec",
        "-i",
        `supabase_db_${projectId}`,
        "psql",
        "-U",
        "postgres",
        "-d",
        "postgres",
        "-X",
        "-v",
        "ON_ERROR_STOP=1",
        "-Atq",
      ];

  const result = spawnSync(command, args, {
    encoding: "utf8",
    env: useLocalPsql ? { ...process.env, PGDATABASE: databaseUrl } : process.env,
    input: `set time zone 'UTC';\n${sql}`,
    maxBuffer: 8 * 1024 * 1024,
  });

  if (result.status !== 0) {
    fail(`psql failed: ${result.stderr || `exit code ${result.status}`}`);
  }

  return result.stdout.trim();
}

/** Labelled lines (`key:value`) into a multimap, because several assertions expect 0 or 2 rows. */
function labelled(output) {
  const table = new Map();
  for (const line of output.split("\n")) {
    if (!line) continue;
    const separator = line.indexOf(":");
    if (separator < 0) continue;
    const key = line.slice(0, separator);
    const list = table.get(key) ?? [];
    list.push(line.slice(separator + 1));
    table.set(key, list);
  }
  return table;
}

function one(table, key) {
  const values = table.get(key) ?? [];
  if (values.length !== 1) {
    fail(`expected exactly one \`${key}\` row from the database, got ${values.length}`);
  }
  return values[0];
}

// ---------------------------------------------------------------------------------------------
// Cleanup
// ---------------------------------------------------------------------------------------------

/**
 * The seven row guards that stand between this script and deleting its own fixture, and how each is
 * handled. `enabled=A` means ENABLE ALWAYS, which is the point of the three compliance guards: a
 * replication session cannot switch them off.
 *
 * `enrollment_milestones_append_only` (migration 350, R4A-05) is the newest and reaches this script
 * twice: once through the explicit milestone delete below, and once through the ON DELETE CASCADE
 * from `clients`. A completion row is evidence for every other caller, so the guard is ALWAYS and
 * this script lifts it by name for one transaction rather than the table being left erasable.
 */
const ROW_GUARDS = [
  { table: "consents", trigger: "consents_append_only", restore: "enable always" },
  { table: "consents", trigger: "consents_prevent_change", restore: "enable" },
  { table: "esignatures", trigger: "esignatures_append_only", restore: "enable always" },
  { table: "consent_revocations", trigger: "consent_revocations_append_only", restore: "enable always" },
  { table: "enrollment_milestones", trigger: "enrollment_milestones_append_only", restore: "enable always" },
  { table: "audit_log", trigger: "audit_log_prevent_change", restore: "enable" },
  { table: "stage_history", trigger: "stage_history_prevent_change", restore: "enable" },
];

/**
 * Delete every row this run created, in an order the foreign keys allow.
 *
 * The order is not cosmetic. `consent_revocations`, `consumer_subscriptions`, `esignatures` and
 * `idv_sessions` reference `clients` with ON DELETE RESTRICT, so they must go first or the client
 * delete raises. `plans` and `checklist_item_state` reference `analysis_runs` with NO ACTION, so
 * they must go before the runs — including before the cascade that would otherwise remove the runs
 * along with the client. Everything after that cascades off `clients`, and is deliberately left to
 * the cascade rather than enumerated: a child table added by a later migration is then deleted by
 * the database instead of being silently orphaned by a list nobody remembered to update.
 *
 * That last sentence is why `session_replication_role = replica` is NOT used here, even though it
 * is the obvious way to get past the row guards and even though the sibling concurrency verifier
 * uses it. Replica mode disables the internal referential-integrity triggers too, so ON DELETE
 * CASCADE stops firing: the client row disappears and its enrollments, consents, audit rows,
 * stage history and receipts stay behind pointing at nothing. Measured, not theorised — an earlier
 * revision of this script did exactly that and left 44 orphan rows across six tables.
 *
 * So the guards are disabled by name instead, for the length of one transaction, and each is
 * restored to the exact mode it had. The ALTERs are transactional: an abort anywhere in between
 * rolls them back, so there is no window in which a crash leaves a compliance guard off. Nothing
 * else in the repository deletes these rows and nothing should — the local e2e fixtures
 * deliberately leave their evidence behind. This script deletes its own only because its acceptance
 * criterion is that the reserved prefix returns to zero rows, and the RESTRICT edge from
 * `esignatures` to `clients` makes that impossible while the evidence stands.
 *
 * The four deletes between the client and the profile close the other direction. Five tables
 * reference `profiles` with NO ACTION — `enrollment_milestones.completed_by`,
 * `consent_revocations.revoked_by`, `stage_history.changed_by`, `audit_log.actor_profile_id` and
 * `clients` itself — so a row attributed to the fictional consumer but not reachable through its
 * client blocks the profile delete. Keying those on the reserved prefix rather than on the client
 * is deliberate: it means the identity this script mints can always be withdrawn, whatever state a
 * previous run left the database in.
 */
function cleanupReservedRows() {
  const owned = `select id from public.clients where consumer_profile_id::text like '${RESERVED_PREFIX}%'`;
  const disable = ROW_GUARDS.map(
    (guard) => `alter table public.${guard.table} disable trigger ${guard.trigger};`,
  ).join("\n");
  const restore = ROW_GUARDS.map(
    (guard) => `alter table public.${guard.table} ${guard.restore} trigger ${guard.trigger};`,
  ).join("\n");

  runSql(`
begin;
${disable}
delete from public.checklist_item_state where client_id in (${owned});
delete from public.plans where client_id in (${owned});
delete from public.analysis_runs where client_id in (${owned});
delete from public.consumer_subscriptions where client_id in (${owned});
delete from public.idv_sessions where client_id in (${owned});
delete from public.esignatures where client_id in (${owned});
delete from public.consent_revocations where client_id in (${owned});
delete from public.clients where consumer_profile_id::text like '${RESERVED_PREFIX}%';
delete from public.enrollment_milestones where completed_by::text like '${RESERVED_PREFIX}%';
delete from public.consent_revocations where revoked_by::text like '${RESERVED_PREFIX}%';
delete from public.stage_history where changed_by::text like '${RESERVED_PREFIX}%';
delete from public.audit_log where actor_profile_id::text like '${RESERVED_PREFIX}%';
delete from public.profiles where id::text like '${RESERVED_PREFIX}%';
delete from auth.users where id::text like '${RESERVED_PREFIX}%';
${restore}
commit;
`);
}

/**
 * Signal the child, but only after confirming the PID still holds the port this run handed out.
 *
 * PIDs are reused, and a stale metadata file pointing at a recycled PID would otherwise turn
 * cleanup into "kill an arbitrary process", which is the one thing a verifier that shares a machine
 * with other agents must never do. The identity check is `lsof`, not the command line: Next.js
 * rewrites its own process title to `next-server (v16.2.10)`, so by the time the server is up
 * neither the `-p <port>` argument nor the script path is visible in `ps` output.
 */
function stopChild(pid, port) {
  if (!Number.isInteger(pid) || pid <= 1) return "no child recorded";

  const listening = spawnSync(
    "lsof",
    ["-nP", `-iTCP:${port}`, "-sTCP:LISTEN", "-t"],
    { encoding: "utf8" },
  );
  const owners = (listening.stdout ?? "").split("\n").map((line) => line.trim()).filter(Boolean);
  if (owners.length === 0) return `pid ${pid} already gone`;
  if (!owners.includes(String(pid))) {
    return `pid ${pid} no longer holds port ${port} — left alone`;
  }

  try {
    process.kill(-pid, "SIGTERM");
  } catch {
    try {
      process.kill(pid, "SIGTERM");
    } catch {
      return `pid ${pid} could not be signalled`;
    }
  }
  return `pid ${pid} stopped`;
}

function removeMetadata() {
  fs.rmSync(METADATA_PATH, { force: true });
}

/**
 * The child this process spawned, tracked outside `prepare()` so the signal handlers can stop it.
 * During `--prepare` the metadata file does not exist yet, so it cannot be the only record of the
 * PID: an interrupt in that window would otherwise orphan a server nobody knows how to find.
 */
const activeChild = { pid: null, port: null };

// ---------------------------------------------------------------------------------------------
// HTTP
// ---------------------------------------------------------------------------------------------

async function freePort() {
  return new Promise((resolve, reject) => {
    const probe = createServer();
    probe.once("error", reject);
    probe.listen(0, "127.0.0.1", () => {
      const { port } = probe.address();
      probe.close(() => resolve(port));
    });
  });
}

async function call(baseUrl, method, route, profileId, body) {
  const response = await fetch(`${baseUrl}${route}`, {
    body: body === undefined ? undefined : JSON.stringify(body),
    headers: {
      ...(body === undefined ? {} : { "content-type": "application/json" }),
      "x-mf-demo-profile-id": profileId,
    },
    method,
  });
  const text = await response.text();
  let payload = null;
  try {
    payload = JSON.parse(text);
  } catch {
    payload = null;
  }
  return { payload, status: response.status };
}

/**
 * The child runs `next start` against the build already in `.next`, not `next dev`.
 *
 * `NEXT_PUBLIC_SUPABASE_URL` is read from `process.env` at request time in the server bundle rather
 * than inlined at build time, so one env-less build serves every environment and this script does
 * not have to rebuild to point the app at the local stack.
 */
async function startChildServer(port) {
  const logPath = process.env.MF_LIVE_LOG;
  const sink = logPath ? fs.openSync(logPath, "a") : fs.openSync("/dev/null", "a");

  const child = spawn(path.join(WEB_ROOT, "node_modules/.bin/next"), ["start", "-p", String(port)], {
    cwd: WEB_ROOT,
    detached: true,
    env: {
      ...process.env,
      FEATURE_ANALYSIS: "1",
      FEATURE_ENROLLMENT: "1",
      FEATURE_TRACKER: "1",
      NEXT_PUBLIC_SUPABASE_ANON_KEY: stack.ANON_KEY,
      NEXT_PUBLIC_SUPABASE_URL: stack.API_URL,
      SUPABASE_SERVICE_ROLE_KEY: stack.SERVICE_ROLE_KEY,
    },
    stdio: ["ignore", sink, sink],
  });
  child.unref();

  const baseUrl = `http://127.0.0.1:${port}`;
  const deadline = Date.now() + SERVER_READY_TIMEOUT_MS;
  while (Date.now() < deadline) {
    const up = await fetch(`${baseUrl}/api/enroll`).then(
      (response) => response.ok,
      () => false,
    );
    if (up) return { baseUrl, pid: child.pid };
    await delay(500);
  }

  stopChild(child.pid, port);
  fail(`the child application server did not answer on port ${port} within ${SERVER_READY_TIMEOUT_MS}ms`);
}

