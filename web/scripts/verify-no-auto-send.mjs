// Self-test
// ---------------------------------------------------------------------------------------------

/**
 * Plant one violation of each rule in a temporary tree and require the scan to catch all five.
 *
 * The tree mirrors the real layout closely enough that the same `scan()` runs over it unchanged —
 * a self-test against a different code path would prove nothing about the scan that runs in CI.
 */
function runSelfTest() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "no-auto-send-selftest-"));
  try {
    const write = (relativePath, contents) => {
      const absolute = path.join(root, relativePath);
      fs.mkdirSync(path.dirname(absolute), { recursive: true });
      fs.writeFileSync(absolute, contents);
    };

    // A plausible seam, so the graph has something real to walk.
    write("web/src/lib/db/types.ts",
      `export type Db = { rpc: { ${SEND_RPC}: unknown } };\n`);
    write("web/src/lib/support/repository.ts",
      `export const SUPPORT_SEND_MESSAGE_RPC = '${SEND_RPC}';\n` +
      "export function sendMessage() { return null; }\n");
    write("web/src/lib/support/service.ts",
      "import { sendMessage } from './repository.ts';\nexport { sendMessage };\n");
    write("web/src/lib/support/index.ts",
      "export { sendMessage } from './service.ts';\n");
    write("web/src/app/api/support/threads/[id]/messages/route.ts",
      "import { sendMessage } from '@/lib/support';\nexport function POST() { return sendMessage(); }\n");

    // 1. A second file naming the RPC. In TypeScript the name reaches the client as a string
    //    literal, so the string is the call and the string is what has to be caught.
    write("web/src/lib/notifications/relay.ts",
      `const rpc = '${SEND_RPC}';\nexport default rpc;\n`);

    // 1b. The other direction, and the reason rule 1 strips comments: a file that explains in
    //     prose that it cannot reach the send seam has to be allowed to name the seam it cannot
    //     reach. Naming it is not calling it, and a rule that forbids the explanation is a rule
    //     nobody can document in the language of the code it governs.
    write("web/src/lib/notifications/digest.ts",
      `// Nothing here goes near ${SEND_RPC}; a digest is assembled and handed back to the caller.\n` +
      "export function digest() { return []; }\n");

    // 2. A deferral inside the support path that reaches the seam.
    write("web/src/lib/support/retry.ts",
      "import { sendMessage } from './repository.ts';\n" +
      "export function scheduleRetry() {\n  setTimeout(() => sendMessage(), 1000);\n}\n");

    // 2b. A deferral in a client module that reaches the write over HTTP rather than by import.
    //     This is the case the old directory-list scope could not see: it lives in neither support
    //     directory and imports nothing on the seam, so only "it names a support route in code"
    //     puts it in scope. Its sibling below names the same route in a comment and must stay out.
    write("web/src/lib/operator/support-inbox.client.ts",
      "export async function postReply(b) {\n" +
      "  const r = await fetch('/api/support/threads/1/messages', { method: 'POST', body: b });\n" +
      "  if (!r.ok) setTimeout(() => postReply(b), 5000);\n" +
      "  return r;\n}\n");
    write("web/src/lib/operator/inbox-notes.ts",
      "// Notes never post to /api/support/threads/:id/messages; they stay in the operator's tab.\n" +
      "export function note() { setTimeout(() => {}, 10); return null; }\n");

    // 2c. The same deferral hidden behind a decrement on one line. `--` is a comment in SQL and
    //     the decrement operator in TypeScript, and a strip that honours it everywhere blanks the
    //     rest of this line — so the resend below was invisible while the identical statement on
    //     its own line was caught. Rail 1 defeated by one character, in the gate that holds it.
    write("web/src/lib/support/backoff.ts",
      "import { sendMessage } from './repository.ts';\n" +
      "export function drain(n) { while (n--) { setTimeout(() => sendMessage(), 1000); } }\n");

    // 3. A background-shaped entry point on a send path.
    write("web/src/lib/support/reply-worker.ts",
      "import { sendMessage } from './service.ts';\nexport function run() { return sendMessage(); }\n");

    // 4. An AI-author identifier and an `'ai'` author kind.
    write("web/src/lib/support/config-extra.ts",
      "export const autoSend = false;\nexport const kind = { authorKind: 'ai' };\n");

    // 5. A drafts route segment.
    write("web/src/app/(operator)/drafts/page.tsx", "export default function Page() { return null; }\n");

    write("supabase/migrations/101_support_send_guard.sql",
      `create function public.${SEND_RPC}() returns void language sql as $$ select 1 $$;\n`);

    const { findings } = scan({ webRoot: path.join(root, "web"), repoRoot: root });
    const rules = new Set(findings.map((finding) => finding.rule));

    for (const rule of ["single-caller", "deferred-writer", "reachability", "ai-author", "drafts-segment"]) {
      assert.ok(rules.has(rule), `self-test: the scan missed the planted ${rule} violation`);
    }
    // The deferral must be caught as a deferral specifically, not only as a stray entry point.
    assert.ok(
      findings.some((finding) => finding.rule === "deferred-writer" && finding.detail.includes("setTimeout")),
      "self-test: the planted setTimeout was not identified as a deferral",
    );
    assert.ok(
      findings.some((finding) => finding.rule === "reachability" && finding.file.includes("reply-worker")),
      "self-test: the planted worker was not identified as reaching the seam",
    );
    // Rule 1 in both directions, on the same planted tree: the string literal is a call site and
    // must be caught, the comment is a description and must not be. Asserting only the first would
    // pass on a scanner that flags every mention, which is the state this pair was written against.
    assert.ok(
      findings.some((finding) => finding.rule === "single-caller" && finding.file.includes("notifications/relay")),
      "self-test: the planted string-literal RPC name was not caught",
    );
    // Rule 2's derived scope, both directions. The client module reaches the write over HTTP and
    // must be swept; its sibling names the same route only in prose and must not be, or the scope
    // grows to every file that ever documents the support path.
    assert.ok(
      findings.some((finding) => finding.rule === "deferred-writer" && finding.file.includes("support-inbox.client")),
      "self-test: a deferral in a client module that posts to a support route was not caught",
    );
    assert.equal(
      findings.filter((finding) => finding.file.includes("inbox-notes")).length,
      0,
      "self-test: a module naming a support route only in a comment was pulled into the deferral sweep",
    );
    assert.ok(
      findings.some(
        (finding) => finding.rule === "deferred-writer" && finding.file.includes("backoff"),
      ),
      "self-test: a deferral sharing a line with a decrement was blanked away with the `--`",
    );
    assert.equal(
      findings.filter((finding) => finding.file.includes("notifications/digest")).length,
      0,
      "self-test: a comment naming the send RPC was reported as a violation",
    );
    // The other direction: the allow-list has to actually hold. The generated types file names the
    // RPC in every checkout, so if this ever starts being flagged the scan fails on a clean tree
    // and somebody will be tempted to hand-edit a generated file to quiet it.
    assert.equal(
      findings.filter((finding) => finding.file.endsWith("src/lib/db/types.ts")).length,
      0,
      "self-test: the generated types file was flagged despite its allow-list entry",
    );

    return findings.length;
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

// ---------------------------------------------------------------------------------------------
// Entry point
// ---------------------------------------------------------------------------------------------

const RULE_COUNT = 5;

try {
  const selfTestFindings = runSelfTest();

  if (process.argv.includes("--self-test")) {
    console.log(
      `No-auto-send scanner self-test passed: ${RULE_COUNT} rules, ${selfTestFindings} planted findings caught.`,
    );
  } else {
    const result = scan({ webRoot: WEB_ROOT, repoRoot: REPO_ROOT });
    if (result.findings.length > 0) {
      for (const finding of result.findings) {
        console.error(`${finding.file}:${finding.line} — ${finding.rule} — ${finding.detail}`);
      }
      throw new Error(`${result.findings.length} auto-send risk(s) found.`);
    }
    console.log(
      `No-auto-send scan passed: ${result.fileCount} files, ${RULE_COUNT} rules, 0 findings; ` +
        `self-test ${selfTestFindings} findings.`,
    );
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
