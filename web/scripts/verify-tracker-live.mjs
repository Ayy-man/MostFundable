/**
 * Values that must never reach stdout, stderr or the metadata file.
 *
 * Collected as they are discovered rather than filtered at the print site, because the leak this
 * guards against is an error object — a fetch failure or a psql stderr — carrying a URL nobody
 * chose to print. `redact()` runs over everything on the way out.
 */
const secrets = new Set();

function remember(value) {
  if (typeof value === "string" && value.trim().length > 8) secrets.add(value.trim());
  return value;
}

function redact(value) {
  let text = typeof value === "string" ? value : String(value);
  for (const secret of secrets) text = text.split(secret).join("[redacted]");
  return text;
}

function say(line) {
  process.stdout.write(`${redact(line)}\n`);
}

function fail(message) {
  throw new Error(redact(message));
}

