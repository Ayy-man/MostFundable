function collectFiles(root, predicate) {
  if (!fs.existsSync(root)) return [];
  const files = [];
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    const absolute = path.join(root, entry.name);
    if (entry.isDirectory()) files.push(...collectFiles(absolute, predicate));
    else if (predicate(absolute)) files.push(absolute);
  }
  return files;
}

function collectDirectories(root) {
  if (!fs.existsSync(root)) return [];
  const directories = [];
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const absolute = path.join(root, entry.name);
    directories.push(absolute, ...collectDirectories(absolute));
  }
  return directories;
}

const isSource = (file) => /\.(ts|tsx|mts|cts)$/.test(file);
const isTest = (file) => /\.test\.(ts|tsx)$/.test(file);

/**
 * Both strips come from `src/lib/testing/strip-comments.ts`. They were written here first and
 * lived here alone until the repo-wide sweep found twelve hand-rolled copies elsewhere; the shared
 * module is this scanner, lifted, and the two entry points exist because of the two rules below.
 *
 * Rule 1 needs `stripComments`: in TypeScript the RPC name reaches the client as a string literal
 * — `repository.ts` declares it as `SUPPORT_SEND_MESSAGE_RPC = …` and that string is the call —
 * so blanking strings would blind the one rule whose whole job is to find a second file holding
 * that string. Raw text is no better: then no comment in `web/src` may name the seam, and the
 * comment most worth writing is the one on a module explaining that it can never reach it.
 *
 * Rules 2, 3 and 4 need `stripCommentsAndStrings`, or the scanner reads its own documentation as a
 * violation: the draft route carries a comment saying that no `after()` picks a draft up, which is
 * a statement of the property, not a breach of it.
 *
 * The one behavioural change on adopting the shared module is the one worth naming. The local copy
 * honoured `--` as a line comment on every file, TypeScript included, so a decrement blanked the
 * rest of its line: `while (n--) { setTimeout(() => resend(), 1000); }` was invisible to rule 2
 * while the identical statement on its own line was caught. That is rail 1 defeated by one
 * character, in the gate that holds it. `--` is now opt-in and passed only for `.sql`.
 *
 * Both preserve length by replacing each stripped character with a space, so line and column
 * numbers still line up with the original file.
 */

function lineOf(source, offset) {
  return source.slice(0, offset).split("\n").length;
}

function matchesIn(source, pattern) {
  const global = new RegExp(pattern.source, pattern.flags.includes("g") ? pattern.flags : `${pattern.flags}g`);
  const hits = [];
  let match = global.exec(source);
  while (match !== null) {
    hits.push({ index: match.index, text: match[0] });
    if (match.index === global.lastIndex) global.lastIndex += 1;
    match = global.exec(source);
  }
  return hits;
}

// ---------------------------------------------------------------------------------------------
// The import graph
// ---------------------------------------------------------------------------------------------

const IMPORT_PATTERNS = [
  // import … from '…'  /  export … from '…'
  /(?:^|\n)\s*(?:import|export)\s+([\s\S]*?)\s+from\s*['"]([^'"]+)['"]/g,
  // await import('…')
  /import\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
];

/**
 * Resolve an import specifier to a file inside the scanned tree.
 *
 * Handles the three forms this repository uses: an explicit `./x.ts`, a bare `./x` needing an
 * extension, and the `@/` alias for `src/`. Anything that resolves outside the tree — a package,
 * `node:fs` — returns null and drops out of the graph, which is correct: those cannot import
 * the seam back.
 */
function resolveSpecifier(specifier, fromFile, srcRoot) {
  let base;
  if (specifier.startsWith("@/")) base = path.join(srcRoot, specifier.slice(2));
  else if (specifier.startsWith(".")) base = path.resolve(path.dirname(fromFile), specifier);
  else return null;

  const candidates = [
    base,
    `${base}.ts`,
    `${base}.tsx`,
    base.replace(/\.ts$/, ".ts"),
    path.join(base, "index.ts"),
    path.join(base, "index.tsx"),
  ];
  for (const candidate of candidates) {
    if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
  }
  return null;
}

/** `{ file → [{ target, clause }] }`, where `clause` is the raw import clause or `*` for dynamic. */
function buildImportGraph(files, srcRoot) {
  const graph = new Map();
  for (const file of files) {
    const source = fs.readFileSync(file, "utf8");
    const edges = [];

    for (const hit of matchesIn(source, IMPORT_PATTERNS[0])) {
      const match = /(?:import|export)\s+([\s\S]*?)\s+from\s*['"]([^'"]+)['"]/.exec(hit.text);
      if (!match) continue;
      const target = resolveSpecifier(match[2], file, srcRoot);
      if (target) edges.push({ target, clause: match[1] });
    }
    for (const hit of matchesIn(source, IMPORT_PATTERNS[1])) {
      const match = /import\s*\(\s*['"]([^'"]+)['"]\s*\)/.exec(hit.text);
      if (!match) continue;
      const target = resolveSpecifier(match[1], file, srcRoot);
      // A dynamic import gives no specifier list, so it is treated as importing everything.
      if (target) edges.push({ target, clause: "*" });
    }

    graph.set(file, edges);
  }
  return graph;
}

/**
 * The modules that carry `sendMessage` outward from the seam.
 *
 * A module joins the set when it imports — statically or dynamically — a module already in the
 * set, *and* its own source mentions `sendMessage`. Both halves are needed. Module edges alone
 * would sweep in every route that touches the repository chain for any reason, which is most of
 * the phase; the name alone would catch an unrelated `sendMessage` on some other object. Together
 * they pick out the four files that actually pass the call along: the repository defines it, the
 * service calls `repository.sendMessage`, the barrel re-exports it, and the messages route invokes
 * it. The service is why the check cannot be a named-import check — it reaches the seam through a
 * property on an object, and a specifier list would never mention it.
 */
function sendSeamClosure(graph, seedFile, sourceOf) {
  const carriers = new Set([seedFile]);
  let changed = true;

  while (changed) {
    changed = false;
    for (const [file, edges] of graph) {
      if (carriers.has(file)) continue;
      if (!/\bsendMessage\b/.test(sourceOf(file))) continue;
      if (edges.some((edge) => carriers.has(edge.target))) {
        carriers.add(file);
        changed = true;
      }
    }
  }

  return carriers;
}

